export function finding({ ruleId, severity, category, componentRefs = [], paths = [], message, facts = {} }) {
  const normalizedComponents = [...new Set(componentRefs.filter(Boolean))].sort();
  const normalizedPaths = [...new Set(paths)].sort();
  const identityPaths = normalizedComponents.length === 0
    ? normalizedPaths
    : [...new Set(normalizedPaths.map((findingPath) => findingPath.replace(/^\$\.components\[[0-9]+\]/u, "$.components[*]")))];
  const identity = { ruleId, componentRefs: normalizedComponents, paths: identityPaths, facts };
  return {
    findingId: `ccf1-${canonicalJsonSha256V2(identity).slice("sha256:".length, "sha256:".length + 20)}`,
    ruleId,
    severity,
    category,
    componentRefs: normalizedComponents,
    paths: normalizedPaths,
    message,
    facts,
    reviewRoute: severity === "review" ? "independent-review" : severity === "conflict" ? "architecture-and-security-review" : "contract-author"
  };
}

export function push(findings, ruleId, severity, category, records, suffixes, message, facts = {}) {
  const normalized = records.map((record) => record.context ? record : { context: record, path: record.path });
  findings.push(finding({
    ruleId,
    severity,
    category,
    componentRefs: normalized.map(({ context }) => context.componentId),
    paths: normalized.flatMap((record) => suffixes.map((suffix) => `${record.path}.${suffix}`)),
    message,
    facts
  }));
}

export function crossFinding(findings, ruleId, severity, category, records, message, facts = {}) {
  const boundedRecords = records.slice(0, 64);
  findings.push(finding({
    ruleId,
    severity,
    category,
    componentRefs: records.map(({ context }) => context.componentId),
    paths: boundedRecords.map(({ path: recordPath }) => recordPath),
    message,
    facts: records.length > boundedRecords.length
      ? { ...facts, recordCount: records.length, pathsTruncated: true }
      : facts
  }));
}

export function append(map, key, value) {
  if (!map.has(key)) map.set(key, []);
  map.get(key).push(value);
}

export function groupBy(values, keyOf) {
  const groups = new Map();
  for (const value of values) append(groups, keyOf(value), value);
  return groups;
}

export function dedupeRecords(records, identityOf) {
  return [...new Map(records.map((record) => [identityOf(record), record])).values()];
}

export function canonicalVariants(values) {
  return new Set(values.map((value) => canonicalJsonV2(value)));
}

export function uniqueComponents(records) {
  return [...new Set(records.map(({ context }) => context.componentId))];
}
